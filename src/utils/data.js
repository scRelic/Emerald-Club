export const getTableTheme = (themeId) => {
    const legacyThemeIds = {
        green: "table-emerald",
        blue: "table-midnight",
        red: "table-burgundy",
    };
    const normalizedId = legacyThemeIds[themeId] || themeId;

    return shopItems.find((item) => item.category === "tables" && item.id === normalizedId)
        || shopItems.find((item) => item.id === "table-emerald");
};